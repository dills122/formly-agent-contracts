import { mkdir, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath, URL } from 'node:url';

import { extractFormContract } from '../packages/formly-adapter/dist/index.js';

import { APPLICANT_TEST_FORMS } from '../apps/formly-test-app/src/app/forms/applicant/applicant-forms.ts';
import { EDGE_CASE_TEST_FORMS } from '../apps/formly-test-app/src/app/forms/edge-cases/edge-case-forms.ts';
import { OPERATIONS_TEST_FORMS } from '../apps/formly-test-app/src/app/forms/operations/operations-forms.ts';

const definitions = [
  ...APPLICANT_TEST_FORMS,
  ...OPERATIONS_TEST_FORMS,
  ...EDGE_CASE_TEST_FORMS,
].sort((left, right) => left.id.localeCompare(right.id));

const contracts = Object.fromEntries(
  definitions.map((definition) => [
    definition.id,
    extractFormContract({
      formId: definition.id,
      fields: definition.create().fields,
    }).contract,
  ]),
);

const outputPath = fileURLToPath(
  new URL(
    '../apps/formly-test-app/src/app/generated/demo-contracts.ts',
    import.meta.url,
  ),
);
const source = `// Generated by scripts/generate-formly-test-app-contracts.mjs.\n// Do not edit by hand. The browser reads these build-time artifacts; it does not run the Node-only analyzer.\n\nexport const DEMO_CONTRACTS = ${JSON.stringify(contracts, null, 2)} as const;\n`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, source, 'utf8');
process.stdout.write(
  `Generated ${definitions.length} synthetic contracts at ${outputPath}\n`,
);
